  CONSTRAINT fk_ingresos_pagos FOREIGN KEY (id_pago) REFERENCES pagos (id_pago),
  CONSTRAINT fk_ingresos_pase_origen FOREIGN KEY (id_pase_origen) REFERENCES ingresos (id_ingreso) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT chk_ingresos_tipo CHECK ((tipo_ingreso in ('SOCIO','VISITANTE'))),
  CONSTRAINT chk_ingresos_documento CHECK ((tipo_documento in ('DNI','CE'))),
  CONSTRAINT chk_ingresos_referencia CHECK (((tipo_ingreso = 'SOCIO') and (id_socio is not null) and (id_contacto is null) and (id_pago is null) and (id_pase_origen is null)) or ((tipo_ingreso = 'VISITANTE') and (id_socio is null) and (id_contacto is not null) and (id_pago is not null) and (id_pase_origen is null)) or ((tipo_ingreso = 'VISITANTE') and (id_socio is not null) and (id_contacto is null) and (id_pago is not null) and (id_pase_origen is null)) or ((tipo_ingreso = 'VISITANTE') and (id_socio is not null) and (id_contacto is null) and (id_pago is null) and (id_pase_origen is not null))),
  CONSTRAINT chk_ingresos_idempotencia CHECK ((clave_idempotencia IS NULL AND hash_solicitud IS NULL) OR (clave_idempotencia IS NOT NULL AND hash_solicitud IS NOT NULL AND clave_idempotencia COLLATE "C" ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' AND hash_solicitud COLLATE "C" ~ '^[0-9a-f]{64}$')),
