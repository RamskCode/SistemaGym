  fecha_venta_pase date GENERATED ALWAYS AS ((case when ((tipo_ingreso = 'VISITANTE') and (id_pago is not null)) then cast(fecha_hora as date) else NULL end)) STORED,
  clave_idempotencia varchar(36) COLLATE sistemagym_ai_ci DEFAULT NULL,
  hash_solicitud char(64) COLLATE sistemagym_ai_ci DEFAULT NULL,
  PRIMARY KEY (id_ingreso),
  CONSTRAINT uk_ingresos_documento_fecha UNIQUE (tipo_documento,numero_documento,fecha_ingreso),
