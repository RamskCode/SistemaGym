  id_usuario_actor BIGINT NOT NULL,
  fecha_hora_utc TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  tipo_operacion VARCHAR(12) COLLATE sistemagym_ai_ci NOT NULL,
  motivo VARCHAR(500) COLLATE sistemagym_ai_ci NOT NULL,
  estado_anterior VARCHAR(10) COLLATE sistemagym_ai_ci NOT NULL,
  estado_nuevo VARCHAR(10) COLLATE sistemagym_ai_ci NOT NULL,
  fecha_entrada_anterior_utc TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  fecha_salida_anterior_utc TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT NULL,
  fecha_entrada_nueva_utc TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  fecha_salida_nueva_utc TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT NULL,
  PRIMARY KEY (id_auditoria),
  CONSTRAINT fk_auditoria_asistencia_laboral_asistencia
    FOREIGN KEY (id_asistencia) REFERENCES asistencias_laborales (id_asistencia)
    ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_auditoria_asistencia_laboral_actor
    FOREIGN KEY (id_usuario_actor) REFERENCES usuarios (id_usuario)
    ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT chk_auditoria_asistencia_tipo
    CHECK (tipo_operacion IN ('CORRECCION', 'ANULACION')),
  CONSTRAINT chk_auditoria_asistencia_estados
    CHECK ((tipo_operacion = 'CORRECCION'
        AND estado_anterior = 'ACTIVA' AND estado_nuevo = 'ACTIVA')
      OR (tipo_operacion = 'ANULACION'
        AND estado_anterior = 'ACTIVA' AND estado_nuevo = 'ANULADA')),
  CONSTRAINT chk_auditoria_asistencia_intervalos
    CHECK ((fecha_salida_anterior_utc IS NULL
        OR fecha_salida_anterior_utc > fecha_entrada_anterior_utc)
      AND (fecha_salida_nueva_utc IS NULL
        OR fecha_salida_nueva_utc > fecha_entrada_nueva_utc)),
  CONSTRAINT chk_auditorias_asistencia_laboral_id_auditoria_nonnegative CHECK (id_auditoria >= 0),
  CONSTRAINT chk_auditorias_asistencia_laboral_id_asistencia_nonnegative CHECK (id_asistencia >= 0),
  CONSTRAINT chk_auditorias_asistencia_laboral_id_usuario_actor_nonnegative CHECK (id_usuario_actor >= 0)
);

