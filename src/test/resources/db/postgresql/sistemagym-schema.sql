-- Shared trigger function; table-specific triggers are attached after tables and indexes exist.
CREATE FUNCTION sistemagym_set_fecha_actualizacion() RETURNS trigger
LANGUAGE plpgsql
AS 'BEGIN
  IF TG_TABLE_NAME = ''configuraciones'' THEN
    IF NEW.fecha_actualizacion IS NOT DISTINCT FROM OLD.fecha_actualizacion THEN
      NEW.fecha_actualizacion := statement_timestamp()::timestamp without time zone;
    END IF;
  ELSIF TG_TABLE_NAME = ''operaciones_pago_idempotentes'' THEN
    IF NEW.fecha_actualizacion IS NOT DISTINCT FROM OLD.fecha_actualizacion THEN
      NEW.fecha_actualizacion := statement_timestamp()::timestamp without time zone;
    END IF;
  END IF;
  RETURN NEW;
END;';

