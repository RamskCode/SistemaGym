  CONSTRAINT chk_ingresos_id_socio_nonnegative CHECK (id_socio >= 0),
  CONSTRAINT chk_ingresos_id_contacto_nonnegative CHECK (id_contacto >= 0),
  CONSTRAINT chk_ingresos_id_usuario_nonnegative CHECK (id_usuario >= 0),
  CONSTRAINT chk_ingresos_id_pago_nonnegative CHECK (id_pago >= 0),
  CONSTRAINT chk_ingresos_id_pase_origen_nonnegative CHECK (id_pase_origen >= 0)
